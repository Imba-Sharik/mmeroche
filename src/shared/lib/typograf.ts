/** Неразрывный пробел, U+00A0 */
const NBSP = String.fromCharCode(0xa0);

/**
 * Короткое слово, которое не оставляем в конце строки: предлоги, союзы,
 * частицы. Одно- и двухбуквенные ловим по длине, трёхбуквенные — списком,
 * иначе к следующему слову прилипали бы «лук», «сок» и прочее меню.
 *
 * Начало слова — через lookbehind, чтобы он не съедал пробел: иначе в «и в
 * лесу» совпадение «и » забирало пробел перед «в», и «в» оставалось висеть.
 */
const HANGING = /(?<=^|[\s(«"])([а-яё]{1,2}|без|для|над|под|при|про|что|как|или)\s+/giu;

/**
 * Висячие предлоги: склеивает короткое слово со следующим неразрывным
 * пробелом, а тире — с предыдущим словом, чтобы строка не начиналась с «—».
 */
export function typograf(text: string) {
  return text.replace(HANGING, `$1${NBSP}`).replace(/\s+—/g, `${NBSP}—`);
}
